// A shot kind with no art of its own in the skin falls back to the stock
// shape. Dragon's and The OG's uploads carried filled test copies of the
// stock torpedo/hadouken — per the author ("those are actually test versions
// of default ones, so dragon and the og actually has default charge shot
// icons") they use the stock ones.
// The colour a skin's stock-shape shots are drawn in, when it has no art of
// its own for them: DELTA fires boss Delta's white shots (delta.js's
// whiteSprite), everyone else the stock palette colours (undefined).
export function shotTint(skin) { return skin === 'delta' ? 0xffffff : undefined; }

export function hasSkinShot(skin, kind) {
  return !!ART[skin] && (kind === 'torpedo' ? ('torpedo' in ART[skin] || 'torpedo0' in ART[skin]) : kind in ART[skin]);
}

export const SKIN_PNGS = Object.entries(ART).flatMap(([id, keys]) =>
  Object.keys(keys).map(k => `assets/sprites/skins/${id}/${k}.png`));

export function isCostumeUnlocked(id) {
  const c = COSTUMES.find(c => c.id === id);
  if (!c) return false;
  if (!c.unlockedBy) return true;
  if (getUnlockedCostumes().includes(id)) return true;
  if (c.unlockedBy.some(isCleared)) { addUnlockedCostume(id); return true; }
  return false;
}

// Record every costume the current progress has earned — called after a
// Stage Clear and at boot, so a clear is remembered past the fresh-tab wipe.
export function syncCostumeUnlocks() { COSTUMES.forEach(c => isCostumeUnlocked(c.id)); }

// The costume actually in effect: the saved choice if it's still unlocked,
// else the stock ship.
export function getCostumeId() {
  const id = getCostumeSetting();
  return id && ART[id] && isCostumeUnlocked(id) ? id : 'default';
}
export function setCostumeId(id) { setCostumeSetting(id); }

// DELTA plays like the final boss it's earned from (per direct request:
// "Delta's skin doesn't change everything to monochrome. And all his weapon
// sounds must played in reverse (aka take his final boss sprite as
// template)"): every weapon effect is white, and every weapon sound is the
// stock one reversed (Audio.reverse, built on first use, as delta.js does).
export function isMonoSkin(world) { return !!(world.player && world.player.skin === 'delta'); }
// ...and the whole playfield — hazards, crystals, heal orbs, bosses, HUD —
// is drawn monochrome while a level runs (follow-up: '"All" here also
// includes hazards, crystals, healing orbs and boses'). A desaturate filter
// on the stage, kept in world.baseFilters so pause.js restores it on unpause;
// menu.js's endScreen drops it so the end/victory screens keep their colours.
export function monoFilter() {
  try { const f = new PIXI.filters.ColorMatrixFilter(); f.desaturate(); return f; }
  catch (e) { return null; }
}
export function applyMonoSkin(world) {
  if (!isMonoSkin(world)) return;
  try {
    const f = monoFilter();
    if (!f) return;
    world.baseFilters = [f];
    world.stage.filters = world.baseFilters;
  } catch (e) { /* filter unavailable: colours stay, the effects are still white */ }
}
export function skinSound(world, name) {
  if (!isMonoSkin(world)) return name;
  world.audio.reverse && world.audio.reverse(name);
  return name + 'Rev';
}

function scaleFor(skin, key) {
  const [w] = ART[skin][key];
  let designW;
  if (key === 'bullet' && skin === 'og') designW = OG_BULLET_W;
  else if (FIXED_W[key]) designW = FIXED_W[key];
  else if (key.startsWith('torpedo') || key === 'hadouken') designW = w * BULLET_FACTOR;
  else designW = w * SHIP_DESIGN_W[skin] / ART[skin][SHIP_REST_KEY[skin]][0];
  return designW * WORLD_SCALE / (w * TEX_PER_UNIT);
}

export function skinTexture(skin, key) {
  return PIXI.Texture.from(`assets/sprites/skins/${skin}/${key}.png`);
}

// A sprite of one costume, anchored and sized. `mult` scales on top (the
// stock bullet sizes: 0.9 plain, 1 torpedo, 1.2 hadouken, smaller pellets).
export function makeSkinSprite(skin, key, mult = 1) {
  const s = new PIXI.Sprite(skinTexture(skin, key));
  setSkinFrame(s, skin, key, mult);
  return s;
}

// Swap an existing sprite to another costume of the same skin.
export function setSkinFrame(sprite, skin, key, mult = 1) {
  const [, ax, ay] = ART[skin][key];
  sprite.texture = skinTexture(skin, key);
  sprite.anchor.set(ax, ay);
  sprite.scale.set(scaleFor(skin, key) * mult);
  sprite._skinKey = key;
}

// Which ship costume to show, following each upload's own costume script:
//  firework  — Normal/Move, in a colour per weapon (N_/M_ Shotgun/Ball/Sword)
//  dragon    — Fire while the trigger's held, a charged look per weapon once
//              a charge is past ~70% (Scratch: Power > 69), the hadouken
//              look once supercharged (Power = 100)
//  og        — Normal / Move / Charge
//  devilfish — tail swims through its 6 frames while moving
//  delta     — one costume; moving leaves afterimages (see SkinGhost)
export function shipKey(skin, st) {
  const wid = st.weaponId || 'default';
  switch (skin) {
    case 'firework': return (st.moving ? 'move_' : 'normal_') + (ART.firework['normal_' + wid] ? wid : 'default');
    case 'dragon':
      // LINE SLASHER never opens the mouth — not on a slash, a charge or a
      // dash (per direct request); a charged slasher shows its own
      // closed-mouth, red-eyed costume.
      if (wid === 'lineslasher') return st.charging && st.chargeRatio > 0.69 ? 'charge_lineslasher' : 'normal';
      if (st.charging && st.chargeRatio > 0.69) {
        if (st.superReady) return 'charge_super';
        return ART.dragon['charge_' + wid] ? 'charge_' + wid : 'charge_default';
      }
      return st.fireHeld ? 'fire' : 'normal';
    case 'og': return st.charging && st.chargeRatio > 0.69 ? 'charge' : (st.moving ? 'move' : 'normal');
    case 'devilfish': return 'swim' + (st.moving ? Math.floor(st.time * 15) % 6 : 0);
    default: return 'normal';
  }
}

// Bullet costume: 'bullet' | 'torpedo' | 'hadouken'; devil fish's torpedo
// is a 4-frame jellyfish (its source flips to the next costume every 0.1s).
export function bulletKey(skin, kind, t = 0) {
  if (kind === 'torpedo' && skin === 'devilfish') return 'torpedo' + (Math.floor(t / 0.1) % 4);
  return kind;
}

// Delta's afterimage: the source's own "moving → create clone of myself",
// each clone fading out over 10 Scratch frames.
const GHOST_LIFE = 0.33;
export class SkinGhost {
  constructor(world, skin, key, x, y, rotation, scale) {
    this.world = world;
    this.alive = true;
    this.t = 0;
    this.sprite = makeSkinSprite(skin, key);
    this.sprite.scale.set(this.sprite.scale.x * scale);
    this.sprite.rotation = rotation;
    this.sprite.alpha = 0.45;
    this.sprite.zIndex = 9;
    const [sx, sy] = toScreen(x, y);
    this.sprite.position.set(sx, sy);
    world.stage.addChild(this.sprite);
  }
  update(dt) {
    this.t += dt;
    this.sprite.alpha = Math.max(0, 0.45 * (1 - this.t / GHOST_LIFE));
    if (this.t >= GHOST_LIFE) this.destroy();
  }
  destroy() {
    this.alive = false;
    if (!this.sprite.destroyed) this.sprite.destroy();
  }
}
