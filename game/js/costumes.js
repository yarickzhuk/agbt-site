// Per direct request ("in settings add 'Costumes' option... reskins, you
// unlock them when completing levels"), with five uploads, one per level:
// each is a Scratch Player sprite (the ship) plus a Bullet sprite (plain
// shot / break / torpedo / hadouken). The art is rasterized straight from
// those SVG costumes into assets/sprites/skins/<id>/<key>.png at 4 texture
// px per Scratch unit (the kangaroo.js/corn.js raster convention) — several
// skins use more than one colour per costume, which a single-tint shape-JSON
// build can't carry.
//
// The chosen costume is a device preference (settings.js), and so is the
// record of which ones are unlocked: progress itself is wiped on every fresh
// tab, but a costume, once earned, stays earned.
