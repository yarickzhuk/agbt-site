// Ship size: design units per Scratch unit, picked so each skin's resting
// costume lands near the stock ship's 37-unit length (the dragon reads
// bigger, the fish counts its long tail). Bullets: torpedo/hadouken use the
// ratio the stock Hadouken/Torpedo shapes already have to their own Scratch
// costumes (~1.7); plain shots and breaks are sized to a fixed width
// instead, since the uploads range from a 1-unit dot to a 13-unit fish.
const SHIP_DESIGN_W = { firework: 40, dragon: 66, og: 36, devilfish: 58, delta: 36 };
const SHIP_REST_KEY = { firework: 'normal_default', dragon: 'normal', og: 'normal', devilfish: 'swim0', delta: 'normal' };
const BULLET_FACTOR = 1.72;
const FIXED_W = { bullet: 15, break: 9 };
const OG_BULLET_W = 7;   // The OG's plain shot is a tiny dot; 15 wide would read as a blob

// The order the request listed them, after the stock ship.
// DEVIL FISH's downside: one life fewer than the difficulty gives (never
// below 1). main.js clamps the run's lives to this at a level's start, and
// OUTER SPACE's next-stage refill uses it.
export function livesCap(world, skin = getCostumeId()) {
  const n = world.difficulty.startLives;
  return skin === 'devilfish' ? Math.max(1, n - 1) : n;
}

